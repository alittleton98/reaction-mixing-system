import json
import os

SRC_DIR = os.path.dirname(os.path.abspath(__file__))
FORMAT_JSON = os.path.join(SRC_DIR, "file-formats.json")
CPP_OUT = os.path.join(SRC_DIR, "common", "public", "ReactionBinaryFileFormats.generated.h")
CS_OUT = os.path.join(SRC_DIR, "app", "ReactionBinaryFileFormats.g.cs")

json_type_to_csharp_type = {
    "string": "string",
    "double": "double",
    "bool": "bool",
    "int32": "int",
    "int64": "long",
    "uint32": "uint",
    "uint64": "ulong",
    "float": "float",
    "uint8": "byte"
}

json_type_to_cplusplus_type = {
    "string": "std::string",
    "double": "double",
    "bool": "bool",
    "int32": "int32_t",
    "int64": "int64_t",
    "uint32": "uint32_t",
    "uint64": "uint64_t",
    "float": "float",
    "uint8": "uint8_t"
}

HEADER_COMMENT = "// <auto-generated> by generator.py from file-formats.json; do not edit."

# Pascal case for C# and C++ syntax uniformity
def to_pascal(name):
    return "".join(p[:1].upper() + p[1:] for p in name.split("_") if p)

# Combine string and ensure no special chars
def to_identifier(name):
    return "".join(c if c.isalnum() else "_" for c in name)


def write_if_changed(path, text):
    text = text.replace("\n", "\r\n")
    if os.path.exists(path):
        with open(path, "r", newline="") as f:
            if f.read() == text:
                return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="") as f:
        f.write(text)


INT_RANGES = {
    "int32": (-2**31, 2**31 - 1),
    "int64": (-2**63, 2**63 - 1),
    "uint32": (0, 2**32 - 1),
    "uint64": (0, 2**64 - 1),
    "uint8": (0, 2**8 - 1),
}

# Integer literal suffixes, keyed by json type: (C++, C#)
INT_SUFFIXES = {
    "int32": ("", ""),
    "int64": ("LL", "L"),
    "uint32": ("u", "u"),
    "uint64": ("ull", "UL"),
    "uint8": ("", ""),
}

def validate_default(name, json_type, value):
    if json_type == "string":
        ok = isinstance(value, str)
    elif json_type == "bool":
        ok = isinstance(value, bool)
    elif json_type in ("float", "double"):
        ok = isinstance(value, (int, float)) and not isinstance(value, bool)
    else:
        lo, hi = INT_RANGES[json_type]
        ok = isinstance(value, int) and not isinstance(value, bool) and lo <= value <= hi
    if not ok:
        raise ValueError(f"Invalid default {value!r} for {json_type} field '{name}' in {FORMAT_JSON}")


def is_zero_default(json_type, value):
    return value is None or value == ("" if json_type == "string" else 0)


def float_literal(value):
    text = repr(float(value))
    return text if any(c in text for c in ".e") else text + ".0"


def literal(json_type, value, lang):
    """Formats a scalar default value as a C++ (lang="cpp") or C# (lang="cs") literal."""
    if json_type == "string":
        return json.dumps(value)
    if json_type == "bool":
        return "true" if value else "false"
    if json_type == "float":
        return float_literal(value) + "f"
    if json_type == "double":
        return float_literal(value)
    cpp_suffix, cs_suffix = INT_SUFFIXES[json_type]
    return f"{value}{cpp_suffix if lang == 'cpp' else cs_suffix}"


def cpp_type(json_type, dimensions):
    result = json_type_to_cplusplus_type[json_type]
    for size in reversed(dimensions):
        result = f"std::array<{result}, {size}>"
    return result


def cs_type_and_init(json_type, dimensions, default):
    cs_type = json_type_to_csharp_type[json_type]
    if dimensions:
        commas = "," * (len(dimensions) - 1)
        sizes = ", ".join(str(d) for d in dimensions)
        return f"{cs_type}[{commas}]", f" = new {cs_type}[{sizes}];"
    if not is_zero_default(json_type, default):
        return cs_type, f" = {literal(json_type, default, 'cs')};"
    return cs_type, ' = "";' if json_type == "string" else ""


def cpp_array_fill(name, json_type, dimensions, default):
    """Fills an array member in place, avoiding a large temporary on the stack."""
    lines, target = [], name
    for depth in range(len(dimensions) - 1):
        lines.append("\t\t" + "\t" * depth + f"for (auto& d{depth} : {target})")
        target = f"d{depth}"
    lines.append("\t\t" + "\t" * (len(dimensions) - 1) + f"{target}.fill({literal(json_type, default, 'cpp')});")
    return lines


def cs_array_fill(name, json_type, dimensions, default):
    lines, indices = [], []
    for depth, _ in enumerate(dimensions):
        lines.append("        " + "    " * depth + f"for (int i{depth} = 0; i{depth} < {name}.GetLength({depth}); i{depth}++)")
        indices.append(f"i{depth}")
    lines.append("        " + "    " * len(dimensions) + f"{name}[{', '.join(indices)}] = {literal(json_type, default, 'cs')};")
    return lines


def generate_cpp(struct_name, version, fields):
    lines = [HEADER_COMMENT, "#pragma once", "#include <array>", "#include <cstdint>", "#include <string>", ""]
    lines.append(f"constexpr uint32_t {struct_name}_Version = {version};")
    lines.append("")
    lines.append(f"struct {struct_name}")
    lines.append("{")
    array_fills = []
    for name, json_type, dimensions, description, default in fields:
        if description:
            lines.append(f"\t/// {description}")
        init = ""
        if not is_zero_default(json_type, default):
            if dimensions:
                array_fills.append(cpp_array_fill(name, json_type, dimensions, default))
            else:
                init = literal(json_type, default, "cpp")
        lines.append(f"\t{cpp_type(json_type, dimensions)} {name}{{{init}}};")
    if array_fills:
        lines.append("")
        lines.append(f"\t{struct_name}()")
        lines.append("\t{")
        for fill in array_fills:
            lines.extend(fill)
        lines.append("\t}")
    lines.append("};")
    return "\n".join(lines) + "\n"


def generate_cs(struct_name, version, fields):
    lines = [HEADER_COMMENT, "namespace ReactionMixingSystem;", ""]
    lines.append(f"public class {struct_name}")
    lines.append("{")
    lines.append(f"    public const uint Version = {version};")
    lines.append("")
    array_fills = []
    for name, json_type, dimensions, description, default in fields:
        if description:
            lines.append(f"    /// <summary>{description}</summary>")
        cs_type, init = cs_type_and_init(json_type, dimensions, default)
        lines.append(f"    public {cs_type} {to_pascal(name)} {{ get; set; }}{init}")
        if dimensions and not is_zero_default(json_type, default):
            array_fills.append(cs_array_fill(to_pascal(name), json_type, dimensions, default))
    if array_fills:
        lines.append("")
        lines.append(f"    public {struct_name}()")
        lines.append("    {")
        for fill in array_fills:
            lines.extend(fill)
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    with open(FORMAT_JSON, "r") as f:
        fmt = json.load(f)

    struct_name = to_pascal(to_identifier(fmt["name"].replace("-", "_")))
    version = fmt["version"][0]

    fields = []
    for field in fmt["fields"]:
        name, json_type = field["name"], field["type"]
        if json_type not in json_type_to_cplusplus_type:
            raise ValueError(f"Unknown type '{json_type}' for field '{name}' in {FORMAT_JSON}")
        dimensions = field.get("dimensions", [])
        # Arrays take a single scalar default that every element is filled with.
        default = field.get("default")
        if default is not None:
            validate_default(name, json_type, default)
        fields.append((name, json_type, dimensions, field.get("description", ""), default))

    write_if_changed(CPP_OUT, generate_cpp(struct_name, version, fields))
    write_if_changed(CS_OUT, generate_cs(struct_name, version, fields))


if __name__ == "__main__":
    main()
